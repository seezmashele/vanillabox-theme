package main

import "fmt"

// identity is who the theme says it is. KDE asks for the same handful of facts
// in three different formats, and the installer wants the version in a fourth,
// so all four are written from one place.
type identity struct {
	Name          string `json:"name"`
	StyleID       string `json:"styleId"`
	LookAndFeelID string `json:"lookAndFeelId"`
	AuroraeID     string `json:"auroraeId"`

	Version     string `json:"version"`
	Author      string `json:"author"`
	Email       string `json:"email"`
	License     string `json:"license"`
	Description string `json:"description"`
}

// kPluginMetadata renders the KPlugin block both Plasma packages use, differing
// only in the id and the trailing key that says what kind of package it is.
func (id identity) kPluginMetadata(pluginID, tailKey, tailValue string) string {
	return fmt.Sprintf(`{
    "KPlugin": {
        "Authors": [
            {
                "Email": "%s",
                "Name": "%s"
            }
        ],
        "Description": "%s",
        "Id": "%s",
        "License": "%s",
        "Name": "%s",
        "Version": "%s"
    },
    "%s": "%s"
}
`, id.Email, id.Author, id.Description, pluginID, id.License, id.Name, id.Version, tailKey, tailValue)
}

// desktopEntry renders the Aurorae theme's metadata, which predates the JSON
// format the Plasma packages use and is still read as an ini.
func (id identity) desktopEntry() string {
	return fmt.Sprintf(`[Desktop Entry]
Name=%s
Comment=%s
Type=Service
X-KDE-PluginInfo-Author=%s
X-KDE-PluginInfo-Email=%s
X-KDE-PluginInfo-Name=%s
X-KDE-PluginInfo-Version=%s
X-KDE-PluginInfo-License=%s
`, id.Name, id.Description, id.Author, id.Email, id.AuroraeID, id.Version, id.License)
}

// versionSource is the installer's copy of the version. It is Go rather than
// something read at runtime so that `vanillabox --version` still answers when
// the asset directory cannot be found at all.
func (id identity) versionSource() string {
	return fmt.Sprintf(`// Code generated by internal/gen from spec/tokens.json. DO NOT EDIT.

package theme

// Version is the theme's version, and the installer's.
const Version = %q
`, id.Version)
}
